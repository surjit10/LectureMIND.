# evaluation/knowledge_graph/relation_auditor.py
# Read-only Relation Extraction Quality, Direction, and Grounding Auditor.
#
# Audits relations extracted by Stage A9 without mutating any files.
# Evaluates:
#   1. Referential integrity (source & target IDs exist)
#   2. Relation type validity against RelationType enum
#   3. Directional plausibility (exact breakdown of correct, reversed, type-mismatch, unmatched)
#   4. Evidence tiering (DIRECT_EVIDENCE, INDIRECT_EVIDENCE, CO_OCCURRENCE_ONLY, NO_EVIDENCE)
#   5. Triple separation: lecture_supported vs factually_correct vs pedagogical_prerequisite
#   6. Cross-chunk relation analysis (same_chunk vs cross_chunk ratio)
#   7. Gold-standard comparison against relation_gold.json

import json
import logging
import re
from collections import Counter
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

from schemas.enums import RelationType

logger = logging.getLogger(__name__)

# Relational action verbs indicating direct syntactic/semantic links
_RELATION_INDICATORS = re.compile(
    r"\b(require|requires|used\s+in|uses|work\s+using|operates\s+on|creates|induce|induces|"
    r"emits|guides|reduce|reduces|heats\s+up|increase|increases|decrease|decreases|"
    r"caused\s+by|disturbs|forces|means\s+that|known\s+as|loss|connect|connected|wired)\b",
    re.IGNORECASE,
)

# Known semantic direction constraints based on physical and causal principles:
# Maps (source_concept, relation, target_concept) to expected validity.
# This list is intentionally extendable per lecture/domain; the two entries
# below encode Faraday-induction directions for the electrical-engineering
# Transformer lecture and are kept as the built-in default.
_PHYSICAL_DIRECTION_RULES = [
    # Faraday's law: Electromotive Force is derived from changing Magnetic Field
    {
        "source": "magnetic field",
        "relation": "DERIVED_FROM",
        "target": "electromotive force",
        "expected_source": "electromotive force",
        "expected_target": "magnetic field",
        "reason": "Faraday's Law of Induction states that changing magnetic flux induces Electromotive Force (EMF). Thus, EMF is DERIVED_FROM Magnetic Field, not vice versa.",
    },
    # Sinusoidal waveform is generated by AC generator / characterizes AC current
    {
        "source": "magnetic field",
        "relation": "DERIVED_FROM",
        "target": "sinusoidal waveform",
        "expected_source": "magnetic field",
        "expected_target": "alternating current",
        "reason": "A magnetic field is physically generated by alternating current, not directly derived from the mathematical sinusoidal waveform.",
    },
]


def _get_chunk_text(c: Dict[str, Any]) -> str:
    """Safely combine all available textual fields for a chunk."""
    parts = [
        c.get("transcript") or "",
        c.get("text") or "",
        c.get("ocr_text") or "",
        c.get("visual_context") or "",
    ]
    return " ".join(p.strip() for p in parts if p).strip()


@dataclass
class RelationIssue:
    relation_id: str
    source_name: str
    relation: str
    target_name: str
    issue_type: str  # "DANGLING_ENTITY", "INVALID_TYPE", "SUSPICIOUS_DIRECTION", "NO_EVIDENCE", "DUPLICATE"
    reason: str
    severity: str    # "HIGH", "MEDIUM", "LOW"


@dataclass
class RelationAuditResult:
    total_relations: int = 0
    valid_syntax_count: int = 0
    dangling_entity_count: int = 0
    duplicate_relation_count: int = 0
    suspicious_direction_count: int = 0
    
    # Evidence Grounding Tiers
    direct_evidence_count: int = 0
    indirect_evidence_count: int = 0
    co_occurrence_only_count: int = 0
    no_evidence_count: int = 0
    evidence_coverage_rate: float = 0.0  # (direct + indirect) / total
    
    # Semantic Separation Counts
    lecture_supported_count: int = 0
    factually_correct_count: int = 0
    
    # Cross-Chunk Analysis
    same_chunk_count: int = 0
    cross_chunk_count: int = 0
    cross_chunk_ratio: float = 0.0
    
    # Direction Accounting Breakdown
    correct_direction_count: int = 0
    reversed_direction_count: int = 0
    relation_type_mismatch_count: int = 0
    unmatched_relation_count: int = 0
    gold_matched_direction_accuracy: Optional[float] = None  # correct / (correct + reversed)
    overall_direction_accuracy: Optional[float] = None        # correct / total_relations
    direction_accuracy: Optional[float] = None               # Alias for backwards-compat (overall)
    direction_breakdown: Dict[str, Any] = field(default_factory=dict)
    
    # Gold-standard metrics (None if gold data not evaluated)
    gold_relation_precision: Optional[float] = None
    gold_relation_recall: Optional[float] = None
    gold_relation_f1: Optional[float] = None
    gold_evaluation_method: Optional[str] = None
    gold_relation_count: int = 0
    matched_gold_relation_count: int = 0
    tp_relation_count: int = 0
    
    issues: List[Dict[str, Any]] = field(default_factory=list)
    relation_details: List[Dict[str, Any]] = field(default_factory=list)


def _find_evidence_tier(
    source_name: str,
    target_name: str,
    chunks: List[Dict[str, Any]],
) -> Tuple[str, Optional[str], Optional[str], Optional[float], Optional[float]]:
    """
    Search lecture chunks to evaluate evidence tier between source and target.
    
    Returns:
        (evidence_tier, chunk_id, snippet, start_time, end_time)
        evidence_tier is one of: DIRECT_EVIDENCE, INDIRECT_EVIDENCE, CO_OCCURRENCE_ONLY, NO_EVIDENCE
    """
    s_norm = source_name.lower().strip()
    t_norm = target_name.lower().strip()
    
    best_tier = "NO_EVIDENCE"
    best_chunk_id = None
    best_snippet = None
    best_start = None
    best_end = None

    for c in chunks:
        cid = c.get("chunk_id", "")
        text = _get_chunk_text(c)
        text_lower = text.lower()

        if s_norm not in text_lower or t_norm not in text_lower:
            continue

        # Both entities appear in this chunk. Now split into sentences.
        sentences = re.split(r"(?<=[.!?])\s+", text)
        
        # Check for co-occurrence in the exact same sentence
        same_sentence = False
        sentence_has_rel_indicator = False
        matching_sentence = ""

        for s in sentences:
            sl = s.lower()
            if s_norm in sl and t_norm in sl:
                same_sentence = True
                matching_sentence = s.strip()
                if _RELATION_INDICATORS.search(s):
                    sentence_has_rel_indicator = True
                break

        if same_sentence and sentence_has_rel_indicator:
            # DIRECT_EVIDENCE found! This is the strongest evidence tier.
            return (
                "DIRECT_EVIDENCE",
                cid,
                matching_sentence,
                c.get("start_time"),
                c.get("end_time"),
            )

        if same_sentence:
            if best_tier not in ("DIRECT_EVIDENCE", "INDIRECT_EVIDENCE"):
                best_tier = "INDIRECT_EVIDENCE"
                best_chunk_id = cid
                best_snippet = matching_sentence
                best_start = c.get("start_time")
                best_end = c.get("end_time")
        else:
            if best_tier == "NO_EVIDENCE":
                best_tier = "CO_OCCURRENCE_ONLY"
                best_chunk_id = cid
                best_snippet = f"Source and target co-occur in chunk {cid} across different sentences."
                best_start = c.get("start_time")
                best_end = c.get("end_time")

    return (best_tier, best_chunk_id, best_snippet, best_start, best_end)


def audit_relations(
    relations: List[Dict[str, Any]],
    entities: List[Dict[str, Any]],
    chunks: List[Dict[str, Any]],
    gold_relations_path: Optional[str | Path] = None,
    direction_rules: Optional[List[Dict[str, str]]] = None,
    non_factual_name_markers: Optional[List[str]] = None,
) -> RelationAuditResult:
    """
    Perform a comprehensive, read-only audit of extracted relations.

    Args:
        direction_rules: Optional per-domain direction rules (same schema as
            ``_PHYSICAL_DIRECTION_RULES``). Defaults to the built-in rules.
        non_factual_name_markers: Optional list of substring markers; any
            relation whose source name contains one is marked not factually
            correct (used to flag known extraction artifacts, e.g. clausal
            fragments like "us a sinusoidal ...").
    """
    total = len(relations)
    entity_map = {e["entity_id"]: e["name"] for e in entities}
    
    # Map entities to chunks from multimodal chunks text
    entity_chunks: Dict[str, Set[str]] = {e["entity_id"]: set(e.get("chunk_ids") or []) for e in entities}
    for eid, name in entity_map.items():
        if not entity_chunks[eid]:
            n_low = name.lower()
            for c in chunks:
                txt = _get_chunk_text(c).lower()
                if n_low in txt:
                    entity_chunks[eid].add(c.get("chunk_id", ""))

    issues: List[RelationIssue] = []
    details: List[Dict[str, Any]] = []

    if direction_rules is None:
        direction_rules = _PHYSICAL_DIRECTION_RULES
    if non_factual_name_markers is None:
        non_factual_name_markers = ["us a sinusoidal"]

    valid_rel_types = {rt.value for rt in RelationType}
    seen_pairs: Set[Tuple[str, str, str]] = set()

    dangling_count = 0
    duplicate_count = 0
    suspicious_direction_count = 0
    direct_ev_count = 0
    indirect_ev_count = 0
    co_occur_count = 0
    no_ev_count = 0
    same_chunk_count = 0
    cross_chunk_count = 0
    lecture_supported_count = 0
    factually_correct_count = 0

    for r in relations:
        rid = r.get("relation_id", "")
        src_id = r.get("source_entity_id") or r.get("source_id", "")
        tgt_id = r.get("target_entity_id") or r.get("target_id", "")
        rel_type = r.get("relation") or r.get("relation_type", "")

        src_name = entity_map.get(src_id, f"UNKNOWN_ENTITY({src_id})")
        tgt_name = entity_map.get(tgt_id, f"UNKNOWN_ENTITY({tgt_id})")

        # 1. Referential Integrity
        is_dangling = False
        if src_id not in entity_map:
            issues.append(RelationIssue(
                relation_id=rid,
                source_name=src_name,
                relation=rel_type,
                target_name=tgt_name,
                issue_type="DANGLING_ENTITY",
                reason=f"Source entity ID '{src_id}' does not exist in entities.json.",
                severity="HIGH",
            ))
            is_dangling = True
        if tgt_id not in entity_map:
            issues.append(RelationIssue(
                relation_id=rid,
                source_name=src_name,
                relation=rel_type,
                target_name=tgt_name,
                issue_type="DANGLING_ENTITY",
                reason=f"Target entity ID '{tgt_id}' does not exist in entities.json.",
                severity="HIGH",
            ))
            is_dangling = True

        if is_dangling:
            dangling_count += 1

        # 2. Relation Type Validation
        if rel_type not in valid_rel_types:
            issues.append(RelationIssue(
                relation_id=rid,
                source_name=src_name,
                relation=rel_type,
                target_name=tgt_name,
                issue_type="INVALID_TYPE",
                reason=f"Relation type '{rel_type}' is not in RelationType enum ({valid_rel_types}).",
                severity="HIGH",
            ))

        # 3. Duplicate Detection
        pair_key = (src_id, rel_type, tgt_id)
        if pair_key in seen_pairs:
            duplicate_count += 1
            issues.append(RelationIssue(
                relation_id=rid,
                source_name=src_name,
                relation=rel_type,
                target_name=tgt_name,
                issue_type="DUPLICATE",
                reason="Identical (source, relation, target) already declared in relations.",
                severity="MEDIUM",
            ))
        seen_pairs.add(pair_key)

        # 4. Semantic Direction Audit (Checks against physical & causal principles)
        is_suspicious_direction = False
        direction_reason = ""
        for rule in direction_rules:
            if (
                rule["source"].lower() in src_name.lower()
                and rule["relation"] == rel_type
                and rule["target"].lower() in tgt_name.lower()
            ):
                is_suspicious_direction = True
                direction_reason = rule["reason"]
                issues.append(RelationIssue(
                    relation_id=rid,
                    source_name=src_name,
                    relation=rel_type,
                    target_name=tgt_name,
                    issue_type="SUSPICIOUS_DIRECTION",
                    reason=direction_reason,
                    severity="HIGH",
                ))
                suspicious_direction_count += 1
                break

        # 5. Evidence Grounding Tier
        tier, ev_chunk, snippet, t_start, t_end = _find_evidence_tier(src_name, tgt_name, chunks)
        if tier == "DIRECT_EVIDENCE":
            direct_ev_count += 1
            lecture_supported = True
        elif tier == "INDIRECT_EVIDENCE":
            indirect_ev_count += 1
            lecture_supported = True
        elif tier == "CO_OCCURRENCE_ONLY":
            co_occur_count += 1
            lecture_supported = False  # Co-occurrence alone is NOT evidence per guidelines
        else:
            no_ev_count += 1
            lecture_supported = False

        if lecture_supported:
            lecture_supported_count += 1

        # Factual correctness check: false if direction is explicitly reversed
        # or if the source name matches a known extraction-artifact marker.
        factually_correct = not is_suspicious_direction and not any(
            marker.lower() in src_name.lower() for marker in non_factual_name_markers
        )

        if factually_correct:
            factually_correct_count += 1

        # 6. Cross-Chunk Analysis
        src_c = entity_chunks.get(src_id, set())
        tgt_c = entity_chunks.get(tgt_id, set())
        common_chunks = src_c & tgt_c

        if common_chunks:
            same_chunk_count += 1
            is_cross_chunk = False
        else:
            cross_chunk_count += 1
            is_cross_chunk = True

        details.append({
            "relation_id": rid,
            "source_name": src_name,
            "relation": rel_type,
            "target_name": tgt_name,
            "evidence_tier": tier,
            "evidence_chunk_id": ev_chunk,
            "evidence_snippet": snippet,
            "start_time": t_start,
            "end_time": t_end,
            "lecture_supported": lecture_supported,
            "factually_correct": factually_correct,
            "is_cross_chunk": is_cross_chunk,
            "possible_direction_error": is_suspicious_direction,
        })

    ev_cov = ((direct_ev_count + indirect_ev_count) / total) if total > 0 else 0.0
    cross_ratio = (cross_chunk_count / total) if total > 0 else 0.0

    # 7. Gold-Standard Relation Evaluation & Direction Breakdown
    correct_direction_count = 0
    reversed_direction_count = 0
    relation_type_mismatch_count = 0
    unmatched_relation_count = 0
    gold_matched_direction_accuracy = None
    overall_direction_accuracy = None
    direction_breakdown = {}

    gold_relation_precision = None
    gold_relation_recall = None
    gold_relation_f1 = None
    gold_evaluation_method = None
    tp = 0

    if gold_relations_path and Path(gold_relations_path).exists():
        with open(gold_relations_path, "r", encoding="utf-8") as fp:
            gold_data = json.load(fp)

        gold_rels = gold_data.get("relations", [])
        gold_pairs: Set[Tuple[str, str, str]] = set()
        for gr in gold_rels:
            s = gr["source_name"].lower().strip()
            r = gr["relation"].strip()
            t = gr["target_name"].lower().strip()
            gold_pairs.add((s, r, t))

        tp = 0
        correct_list = []
        reversed_list = []
        type_mismatch_list = []
        unmatched_list = []
        claimed_gold: Set[Tuple[str, str, str]] = set()

        for r_detail in details:
            s = r_detail["source_name"].lower().strip()
            rel = r_detail["relation"].strip()
            t = r_detail["target_name"].lower().strip()
            rel_repr = f"{r_detail['source_name']} ==[{rel}]==> {r_detail['target_name']}"

            # Exact forward match (each gold triple may be claimed at most once,
            # across ALL match branches — exact, reverse, and fuzzy — so a
            # duplicate prediction can never score a second TP for one gold).
            if (s, rel, t) in gold_pairs and (s, rel, t) not in claimed_gold:
                claimed_gold.add((s, rel, t))
                tp += 1
                correct_direction_count += 1
                correct_list.append({"relation": rel_repr, "match_type": "EXACT_FORWARD"})
            elif (t, rel, s) in gold_pairs and (t, rel, s) not in claimed_gold:
                claimed_gold.add((t, rel, s))
                # Direct reverse match in gold
                reversed_direction_count += 1
                reversed_list.append({"relation": rel_repr, "gold_relation": f"{t} ==[{rel}]==> {s}"})
            else:
                # Check relation type mismatch on exact entity pair
                same_pair_gold = [g for g in gold_pairs if (g[0] == s and g[2] == t) or (g[0] == t and g[2] == s)]
                if same_pair_gold:
                    relation_type_mismatch_count += 1
                    type_mismatch_list.append({"relation": rel_repr, "gold_matches": same_pair_gold})
                else:
                    # Check fuzzy match against gold relations. Shares the same
                    # claimed_gold set as the exact/reverse branches.
                    fuzzy_matched = False
                    for gs, gr, gt in gold_pairs:
                        if (gs, gr, gt) in claimed_gold:
                            continue
                        if gr == rel and (gs in s or s in gs) and (gt in t or t in gt):
                            claimed_gold.add((gs, gr, gt))
                            tp += 1
                            correct_direction_count += 1
                            correct_list.append({"relation": rel_repr, "match_type": "FUZZY_FORWARD", "gold_match": (gs, gr, gt)})
                            fuzzy_matched = True
                            break
                    if not fuzzy_matched:
                        unmatched_relation_count += 1
                        unmatched_list.append({"relation": rel_repr, "reason": "Not present in gold reference set (or gold triple already matched)"})

        prec = tp / total if total > 0 else 0.0
        rec = tp / len(gold_pairs) if len(gold_pairs) > 0 else 0.0
        f1 = (2 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0

        # Disambiguated Direction Accuracies:
        # 1. Gold-matched direction accuracy: of relations that correspond to a known pair, how many are correct?
        matched_pairs_total = correct_direction_count + reversed_direction_count
        gold_matched_direction_accuracy = round(correct_direction_count / matched_pairs_total, 4) if matched_pairs_total > 0 else 0.0

        # 2. Overall direction acceptance across all extracted relations
        overall_direction_accuracy = round(correct_direction_count / total, 4) if total > 0 else 0.0

        direction_breakdown = {
            "correct_direction_count": correct_direction_count,
            "reversed_direction_count": reversed_direction_count,
            "relation_type_mismatch_count": relation_type_mismatch_count,
            "unmatched_relation_count": unmatched_relation_count,
            "gold_matched_direction_accuracy": gold_matched_direction_accuracy,
            "overall_direction_accuracy": overall_direction_accuracy,
            "correct_examples": correct_list[:5],
            "reversed_examples": reversed_list,
            "type_mismatch_examples": type_mismatch_list,
            "unmatched_examples": unmatched_list[:5],
        }

        gold_relation_precision = round(prec, 4)
        gold_relation_recall = round(rec, 4)
        gold_relation_f1 = round(f1, 4)
        gold_evaluation_method = gold_data.get("metadata", {}).get("annotation_method", "LLM-assisted reference labels, pending human verification")

    return RelationAuditResult(
        total_relations=total,
        valid_syntax_count=total - dangling_count,
        dangling_entity_count=dangling_count,
        duplicate_relation_count=duplicate_count,
        suspicious_direction_count=suspicious_direction_count,
        direct_evidence_count=direct_ev_count,
        indirect_evidence_count=indirect_ev_count,
        co_occurrence_only_count=co_occur_count,
        no_evidence_count=no_ev_count,
        evidence_coverage_rate=round(ev_cov, 4),
        lecture_supported_count=lecture_supported_count,
        factually_correct_count=factually_correct_count,
        same_chunk_count=same_chunk_count,
        cross_chunk_count=cross_chunk_count,
        cross_chunk_ratio=round(cross_ratio, 4),
        correct_direction_count=correct_direction_count,
        reversed_direction_count=reversed_direction_count,
        relation_type_mismatch_count=relation_type_mismatch_count,
        unmatched_relation_count=unmatched_relation_count,
        gold_matched_direction_accuracy=gold_matched_direction_accuracy,
        overall_direction_accuracy=overall_direction_accuracy,
        direction_accuracy=overall_direction_accuracy,
        direction_breakdown=direction_breakdown,
        gold_relation_precision=gold_relation_precision,
        gold_relation_recall=gold_relation_recall,
        gold_relation_f1=gold_relation_f1,
        gold_evaluation_method=gold_evaluation_method,
        gold_relation_count=len(gold_pairs) if (gold_relations_path and Path(gold_relations_path).exists()) else 0,
        matched_gold_relation_count=tp,
        tp_relation_count=tp,
        issues=[asdict(i) for i in issues],
        relation_details=details,
    )
